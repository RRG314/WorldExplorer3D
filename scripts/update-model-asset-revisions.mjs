import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {MODEL_ASSET_REVISIONS} from '../app/js/assets/model-asset-revisions.js';
import {MODEL_ASSET_CATALOG} from '../app/js/assets/model-asset-catalog.js';
async function calculateModelAssetRevisions(){
 const revisions={};
 for(const asset of MODEL_ASSET_CATALOG){
  if(!asset.url.startsWith('/app/assets/models/'))throw Error(`Unexpected asset path: ${asset.id}`);
  revisions[asset.id]=createHash('sha256').update(await readFile(new URL(`..${asset.url}`,import.meta.url))).digest('hex').slice(0,16);
 }
 return revisions;
}
export async function assertModelAssetRevisions(){
 const current=await calculateModelAssetRevisions();
 for(const [id,hash] of Object.entries(current))if(MODEL_ASSET_REVISIONS[id]!==hash)throw Error(`Model cache identity is stale for ${id}. Run node scripts/update-model-asset-revisions.mjs before building.`);
}
export async function updateModelAssetRevisions(){
 const revisions=await calculateModelAssetRevisions();
 await writeFile(new URL('../app/js/assets/model-asset-revisions.js',import.meta.url),`// Generated by scripts/update-model-asset-revisions.mjs from bundled GLB bytes.\nexport const MODEL_ASSET_REVISIONS = Object.freeze(${JSON.stringify(revisions,null,2)});\n`);
}
if(process.argv[1]&&new URL(import.meta.url).pathname===process.argv[1])await updateModelAssetRevisions();
