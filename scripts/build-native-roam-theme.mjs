import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

// Presentation only. The browser's reviewed tokens remain the colour authority;
// the platform SDKs retain font scaling, controls, focus and widget backgrounds.
const css = await fs.readFile('styles/world-explorer-tokens.css', 'utf8');
const root = css.match(/:root\s*\{([^}]+)\}/)?.[1];
assert.ok(root, 'Missing shared Roam tokens');
const fields = {background:'bg',card:'panel-solid',surface:'panel-soft',input:'input',
  text:'text',muted:'muted',accent:'action',actionText:'action-text',line:'line',selected:'selected',focus:'focus'};
const colours = Object.entries(fields).map(([name, token]) => {
  const hex = root.match(new RegExp(`--wx-${token}:\\s*(#[0-9a-fA-F]{6})\\s*;`))?.[1];
  assert.ok(hex, `Missing native colour --wx-${token}`);
  return {name, hex:hex.toLowerCase(), rgb:[1,3,5].map(offset=>parseInt(hex.slice(offset,offset+2),16))};
});
const radius = Number(root.match(/--wx-radius:\s*(\d+)px\s*;/)?.[1]);
assert.ok(Number.isFinite(radius) && radius >= 0 && radius <= 32, 'Invalid shared card radius');
const androidName = name => 'portal_roam_' + name.replace(/[A-Z]/g, c=>'_'+c.toLowerCase());
const outputs = new Map([
  ['android/app/src/main/res/values/portal_roam.xml',
    '<!-- Generated by scripts/build-native-roam-theme.mjs from shared browser tokens. -->\n<resources>\n'+
    colours.map(c=>`    <color name="${androidName(c.name)}">${c.hex}</color>`).join('\n')+
    `\n    <dimen name="portal_roam_card_radius">${radius}dp</dimen>\n</resources>\n`],
  ['apple/Shared/PortalStyle.swift',
    '// Generated by scripts/build-native-roam-theme.mjs from shared browser tokens.\n'+
    '#if canImport(SwiftUI)\nimport SwiftUI\n\nenum PortalStyle {\n'+
    colours.map(c=>`    static let ${c.name} = Color(red: ${c.rgb[0]}/255.0, green: ${c.rgb[1]}/255.0, blue: ${c.rgb[2]}/255.0)`).join('\n')+
    `\n    static let cardRadius: CGFloat = ${radius}\n}\n#endif\n`]
]);
for (const [file, content] of outputs) {
  if (process.argv.includes('--check')) assert.equal(await fs.readFile(file,'utf8'), content, `Regenerate native Roam theme: ${file}`);
  else await fs.writeFile(file, content);
}
console.log(JSON.stringify({passed:true,colours:colours.length,files:outputs.size,mode:process.argv.includes('--check')?'check':'generate'}));
