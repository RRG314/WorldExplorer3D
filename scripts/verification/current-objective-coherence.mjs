import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
import { startStaticServer } from './static-server.mjs';
const server=await startStaticServer({rootDir:process.cwd(),ports:[4396]});
const browser=await chromium.launch({channel:'chrome',headless:true});
const dir='output/verification/product-plan';await fs.mkdir(dir,{recursive:true});
const report={scope:'Actual source Space launch and destination UI, plus controlled retained-expedition snapshot; no account or production acceptance',errors:[]};
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.on('pageerror',e=>report.errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.port}/`,{waitUntil:'load'});
 await page.locator('#landingPrimaryCta').click();
 await page.waitForFunction(()=>window.__WE3D_RUNTIME_READY__===true,null,{timeout:90000});
 if(await page.locator('#analyticsConsentDenyBtn').isVisible())await page.locator('#analyticsConsentDenyBtn').click();
 await page.locator('#globeSelectorSpaceBtn').click();
 await page.waitForFunction(()=>{const d=JSON.parse(window.render_game_to_text?.()||'{}');return d.environment==='SPACE_FLIGHT'&&!d.worldLoading;},null,{timeout:120000});
 await page.selectOption('#spaceDestinationSelect','mars');
 await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).currentJourney?.title==='Mars',null,{timeout:15000});
 report.selected=JSON.parse(await page.evaluate(()=>window.render_game_to_text())).currentJourney;
 await page.evaluate(async()=>{const {ctx}=await import('/app/js/shared-context.js?v=55');ctx.getInterstellarExpeditionSnapshot=()=>({state:'completed',campaignResult:{totalPoints:0}});ctx.tutorialUpdate(1);});
 assert.equal(await page.locator('#currentJourneyTitle').innerText(),'Mars');
 await page.locator('#currentJourneyCard').waitFor({state:'visible'});
 await page.screenshot({path:`${dir}/objective-mars.png`});
 await page.locator('#currentJourneyDismiss').click();
 await page.waitForTimeout(500);
 assert.equal(await page.locator('#currentJourneyCard').isVisible(),false);
 await page.selectOption('#spaceDestinationSelect','moon');
 await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).currentJourney?.title==='Moon');
 assert.equal(await page.locator('#currentJourneyCard').isVisible(),true);
 await page.locator('#currentJourneyAction').click();
 report.actionOpened=await page.locator('#universeNavigator').isVisible();
 assert.equal(report.actionOpened,true);
 assert.match(await page.locator('#universeCourseReadout').innerText(),/Moon/);
 assert.doesNotMatch(await page.locator('#universeCourseReadout').innerText(),/NO COURSE SET/);
 await page.screenshot({path:`${dir}/objective-wayfinder.png`});
 assert.deepEqual(report.errors,[]);report.passed=true;
}finally{await fs.writeFile(`${dir}/objective-browser.json`,JSON.stringify(report,null,2));await browser.close();await server.close();}
console.log(JSON.stringify(report));
